/* Small builders keep the seed readable; every record is still plain data. */
const coord = (
  eventId: string,
  status: CoordinationRequest["status"],
  createdAt: string,
  decidedAt: string | null,
): CoordinationRequest => ({
  id: `CR-${eventId.slice(2)}`,
  eventId,
  charityId: "charity-ataa",
  coordinatorId: "demo-charity-01",
  status,
  reason: null,
  note: null,
  createdAt,
  decidedAt,
});

const assign = (
  eventId: string,
  plannedArrivalAt: string,
  assignedAt: string,
  status: Assignment["status"],
): Assignment => ({
  id: `AS-${eventId.slice(2)}`,
  eventId,
  charityId: "charity-ataa",
  representativeId: "demo-field-01",
  plannedArrivalAt,
  assignedBy: "demo-charity-01",
  assignedAt,
  status,
});

const req = (
  id: string,
  listingId: string,
  beneficiaryId: string,
  units: number,
  status: RequestStatus,
  createdAt: string,
  decidedAt: string | null = null,
  confirmation: FoodRequest["confirmation"] = null,
  rejectReason: RequestRejectReason | null = null,
): FoodRequest => ({
  id,
  listingId,
  beneficiaryId,
  units,
  status,
  createdAt,
  decidedAt,
  decidedBy: decidedAt ? "demo-charity-01" : null,
  rejectReason,
  confirmation,
});

const report = (
  id: string,
  status: ReportStatus,
  r: Pick<SurplusReport, "foodType" | "estimatedQuantity" | "readyAt" | "area" | "createdAt"> & Partial<SurplusReport>,
): SurplusReport => ({
  reporterId: "demo-beneficiary-01",
  charityId: "charity-ataa",
  unit: "kg",
  notes: null,
  photoAttached: false,
  infoRequest: null,
  rejectReason: null,
  inspection: null,
  rescue: null,
  ...r,
  id,
  status,
});

const notice = (
  id: string,
  recipientUserId: string,
  kind: NoticeKind,
  params: Notice["params"],
  link: string | null,
  createdAt: string,
  readAt: string | null = null,
): Notice => ({ id, recipientUserId, kind, params, link, createdAt, readAt });

